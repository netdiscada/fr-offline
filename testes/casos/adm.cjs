const { chromium } = require('playwright');
const { acaoFr, IMPRIMIR, fecharVisor } = require('./ui.cjs');
const { initializeTestEnvironment } = require('@firebase/rules-unit-testing');
const { doc, setDoc, getDoc } = require('firebase/firestore');
(async () => {
  const env = await initializeTestEnvironment({ projectId: 'demo-fr', firestore: { host: '127.0.0.1', port: 8086, rules: require('fs').readFileSync(require('path').resolve(__dirname, '../../firestore.rules'), 'utf8') } });
  const r = await (await fetch('http://127.0.0.1:9098/identitytoolkit.googleapis.com/v1/accounts:signUp?key=demo', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'adm@fr.test', password: 'senha123', returnSecureToken: true }) })).json();
  await env.withSecurityRulesDisabled(async c => {
    const db = c.firestore();
    await setDoc(doc(db, 'admins/' + r.localId), {});
    await setDoc(doc(db, 'funcionarios/100'), { rgf: '100', nome: 'Antonio Silva', cargo: 'Motorista', uid: 'celA', aprovado: true });
    await setDoc(doc(db, 'funcionarios/200'), { rgf: '200', nome: 'Bruno Souza', cargo: 'Motorista', uid: 'celB', aprovado: true });
    await setDoc(doc(db, 'funcionarios/300'), { rgf: '300', nome: 'Fernando Alves', cargo: 'ADM', uid: 'celF', aprovado: true });
    await setDoc(doc(db, 'listas/locais'), { itens: { QUATINGA: { texto: 'Quatinga', n: 12 }, QUATNGA: { texto: 'Quatnga', n: 1 } } });
    await setDoc(doc(db, 'frs/fr2'), { id: 'fr2', rgf: '100', condutor: 'Antonio Silva', uid: 'celA', status: 'fechada', data: '2026-10-25', placa: 'GBI-2447', modelo: 'S-10', itinerario: [] });
    await setDoc(doc(db, 'frs/fr1'), { id: 'fr1', rgf: '300', condutor: 'Fernando Alves', cargo: 'ADM', uid: 'celF', status: 'aberta', data: '2026-10-26', placa: 'GBI-2447', modelo: 'S-10', itinerario: [] });
  });
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 400, height: 860 } });
  p.on('pageerror', e => console.log('pageerror', e.message));
  await p.goto('http://localhost:8090/');
  await p.click('#btnRgfAdm');
  await p.fill('#admEmail', 'adm@fr.test'); await p.fill('#admSenha', 'senha123');
  await p.click('#btnAdmEntrar');
  await p.click('[data-aba="frs"]');
  await acaoFr(p, null, 'compartilhar');
  await p.click('[data-escolha="200"]');
  await p.click('#folhaFormOk');
  await p.waitForSelector('text=Compartilhada com Bruno Souza');
  console.log('OK   ADM compartilhou');
  await acaoFr(p, null, 'trocar');
  await p.click('[data-escolha="100"]');
  await p.click('#folhaFormOk');
  await p.waitForSelector('text=26/10/2026 · Antonio Silva');
  await acaoFr(p, 'fr2', 'reabrir');
  await p.click('#confirmaSim');
  await p.waitForSelector('text=FR liberada');
  await p.screenshot({ path: process.argv[2] });
  await p.click('[data-aba="locais"]');
  await p.waitForSelector('text=Quatnga');
  await p.click('[data-local-id="QUATNGA"] [data-local-acao="editar"]');
  await p.fill('#localNome', 'Quatinga');
  await p.click('#folhaFormOk');
  await p.waitForSelector('#confirmaTitulo:has-text("Juntar os dois?")');
  await p.click('#confirmaSim');
  await p.waitForSelector('text=Locais juntados');
  let lx; await env.withSecurityRulesDisabled(async c => { lx = (await getDoc(doc(c.firestore(), 'listas/locais'))).data().itens; });
  console.log(!lx.QUATNGA && lx.QUATINGA.n === 13 ? 'OK   Corrigir "Quatnga" para "Quatinga" juntou os dois (uso 13)' : 'FALHA juntar ' + JSON.stringify(lx));
  try { await p.waitForSelector('text=Quatnga', { state: 'detached', timeout: 5000 }); }
  catch (e) { console.log('DEBUG', (await p.evaluate(() => document.body.innerText)).replace(/\s+/g, ' ').slice(0, 900)); }
  console.log('OK   ADM excluiu local repetido');
  await p.waitForTimeout(800);
  await p.screenshot({ path: process.argv[2].replace('.png', '-locais.png') });
  let d2; await env.withSecurityRulesDisabled(async c => { d2 = (await getDoc(doc(c.firestore(), 'frs/fr2'))).data(); });
  console.log(d2.status === 'aberta' ? 'OK   ADM liberou de novo a FR encerrada' : 'FALHA reabrir ' + d2.status);
  let d; await env.withSecurityRulesDisabled(async c => { d = (await getDoc(doc(c.firestore(), 'frs/fr1'))).data(); });
  console.log(d.rgf === '100' && d.condutor === 'Antonio Silva' && d.compartilhadoUids.join() === 'celB' ? 'OK   ADM trocou para Antônio (banco certo)' : 'FALHA ' + JSON.stringify(d));
  await b.close(); await env.cleanup(); process.exit(0);
})().catch(e => { console.log('ERRO', ((e.stack || '').match(/\w+\.cjs:\d+/) || [''])[0], e.message.split('\n')[0]); process.exit(1); });
